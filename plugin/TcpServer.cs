        /// <summary>
        /// Log file maximum size (1MB) — auto-rotate when exceeded
        /// </summary>
        private const long MAX_LOG_SIZE = 1024 * 1024;

        /// <summary>
        /// Log rotation: rename current log to .1, create new log
        /// </summary>
        private void RotateLogIfNeeded(string logPath)
        {
            try
            {
                var fileInfo = new System.IO.FileInfo(logPath);
                if (fileInfo.Exists && fileInfo.Length > MAX_LOG_SIZE)
                {
                    var backupPath = logPath + ".1";
                    // Delete old backup
                    if (System.IO.File.Exists(backupPath))
                        System.IO.File.Delete(backupPath);
                    // Rename current log
                    System.IO.File.Move(logPath, backupPath);
                }
            }
            catch { }
        }

        private void Log(string msg)
        {
            // Production: NXOpen.LogFile.WriteLine(msg)
            // Development: Console.WriteLine
            System.Diagnostics.Debug.WriteLine(string.Format("[NxMcpPlugin] {0}", msg));
            Console.WriteLine(string.Format("[NxMcpPlugin] {0}", msg));
            // Also write to file for debugging
            try
            {
                var logPath = NxPaths.StartupFile("tcp_server.log");

                // Log rotation check
                RotateLogIfNeeded(logPath);

                System.IO.File.AppendAllText(logPath,
                    string.Format("[{0:HH:mm:ss.fff}] [TcpServer] {1}\n", DateTime.Now, msg));
            }
            catch { }
        }
