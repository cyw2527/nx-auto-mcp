        private string HandlePing(int id, JToken rawParams)
        {
            return JsonProtocol.Serialize(new ResponseMessage
            {
                Id = id,
                Result = new
                {
                    pong = true,
                    timestamp = DateTime.UtcNow.ToString("o"),
                    version = PluginVersion.Full,
                    tool_count = _toolRegistry.ToolCount
                }
            });
        }

        private string HandleGetSelection(int id, JToken rawParams)
        {
            try
            {
                var objects = _monitor.GetSelection();
                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { objects, count = objects.Count }
                });
            }
            catch (Exception ex)
            {
                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Error = string.Format("Failed to get selection: {0}", ex.Message)
                });
            }
        }

        private string HandleGetModelSummary(int id, JToken rawParams)
        {
            try
            {
                var bodies = new List<ModelBodySummary>();
                try
                {
                    dynamic workPart = _session.Parts.Work;
                    if (workPart != null)
                    {
                        foreach (dynamic body in workPart.Bodies)
                        {
                            int faceCount = 0, edgeCount = 0;
                            try { dynamic faces = body.GetFaces(); faceCount = faces.Length; } catch { }
                            try { dynamic edges = body.GetEdges(); edgeCount = edges.Length; } catch { }
                            bodies.Add(new ModelBodySummary
                            {
                                Name = body.Name ?? "",
                                FaceCount = faceCount,
                                EdgeCount = edgeCount
                            });
                        }
                    }
                }
                catch { }
                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { bodies, count = bodies.Count }
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Failed to get model summary: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Execute tool — unified tool call interface
        ///
        /// Request format:
        ///   { "method": "tool", "id": 1, "params": { "tool": "nx_extrude", "distance": 10, ... } }
        ///
        /// Response format:
        ///   { "id": 1, "result": { "success": true, "message": "...", "data": {...} } }
        /// </summary>
        private string HandleTool(int id, JToken rawParams)
        {
            if (rawParams == null || !(rawParams is JObject))
                return JsonError(id, "Missing params field, must include tool name and parameters");

            try
            {
                var jObj = (JObject)rawParams;
                var toolName = jObj["tool"] != null ? jObj["tool"].Value<string>() : null;

                if (string.IsNullOrEmpty(toolName))
                    return JsonError(id, "Missing tool field in params");

                var tool = _toolRegistry.GetTool(toolName);
                if (tool == null)
                {
                    var toolNames = new List<string>(_toolRegistry.ListToolNames());
                    var available = string.Join(", ", toolNames.ToArray());
                    return JsonError(id, string.Format("Unknown tool: {0}. Available tools: {1}", toolName, available));
                }

                Log(string.Format("Execute tool: {0}, Dispatcher={1}", toolName, MainThreadDispatcher.IsInitialized));

                // Auto-inject user-selected face tags — resolves "selected face parameters not passed" issue
                // If caller did not explicitly provide face_tags or faces_to_remove, extract from current selection
                if (jObj["face_tags"] == null && jObj["faces_to_remove"] == null)
                {
                    var selection = _monitor.GetSelection();
                    var faceTags = new JArray();
                    foreach (var obj in selection)
                    {
                        if (obj.Type == "Face")
                            faceTags.Add(obj.Tag);
                    }
                    if (faceTags.Count > 0)
                    {
                        jObj["face_tags"] = faceTags;
                        Log(string.Format("Auto-injected {0} selected faces: {1}", faceTags.Count,
                            string.Join(",", faceTags.Select(t => t.Value<int>()))));
                    }
                }

                // ★ Work part guard (2026-09-10, M-005b) — see WorkPartGuard.cs
                //   Background: OpenBaseDisplay in probes/scripts can switch the work part away, causing subsequent tools
                //   to operate on the wrong part (previously caused false failures where tools returned empty results).
                //   Tools whose responsibility is "switch active part" are explicitly declared in ExemptTools; guard does not intervene.
                bool guardOn = !WorkPartGuard.IsExempt(toolName);

                // Dispatch tool execution to NX main thread — NXOpen API requires main thread execution
                JObject result = null;
                Rules.RuleValidateResult ruleResult = null;
                if (!MainThreadDispatcher.Invoke(() => {
                    Log(string.Format("[Dispatcher] >>> Execute tool on main thread: {0}", toolName));

                    // Snapshot — must be done on main thread (NXOpen API thread constraint)
                    // ★Stores both {Work, Display}: SetWork is only valid within display context (see WorkPartGuard class comments)
                    WorkPartGuard.Snapshot guardBefore = null;
                    if (guardOn)
                    {
                        string snapErr;
                        guardBefore = WorkPartGuard.Take((object)_session, out snapErr);
                        if (snapErr != null)
                            Log(string.Format("[WorkPartGuard] Snapshot failed, skipping guard this time: {0}", snapErr));
                    }

                    // Engineering rule check — before execution, on main thread (CheckFn may read NX geometry).
                    // Only record results, no interception here.
                    try
                    {
                        ruleResult = _rules.Validate(toolName, jObj);
                    }
                    catch (Exception rex)
                    {
                        Log(string.Format("[RuleEngine] Rule check exception, skipping this time: {0}", rex.Message));
                    }

                    result = tool.Execute(_session, jObj);

                    // Restore — only acts when work part was actually switched; zero overhead if untouched
                    if (guardOn && guardBefore != null && result != null)
                    {
                        JObject guardNote = WorkPartGuard.Restore((object)_session, guardBefore);
                        if (guardNote != null)
                        {
                            if (guardNote["restore_error"] != null)
                                Log(string.Format("[WorkPartGuard] ★Restore failed ({0}): {1}", toolName, guardNote["restore_error"]));
                            else
                                Log(string.Format("[WorkPartGuard] Restored work part: {0} -> {1} (tool {2} switched away{3})",
                                    guardNote["from"], guardNote["restored_to"], toolName,
                                    guardNote["display_restored_to"] != null
                                        ? ", display also restored to " + guardNote["display_restored_to"] : ""));
                            if (guardNote["display_restore_error"] != null)
                                Log(string.Format("[WorkPartGuard] ★Display restore failed ({0}): {1}", toolName, guardNote["display_restore_error"]));

                            // Report faithfully, not silently — contamination should be visible
                            JObject gdata = result["data"] as JObject;
                            if (gdata == null) { gdata = new JObject(); result["data"] = gdata; }
                            gdata["work_part_guard"] = guardNote;
                        }
                    }

                    Log(string.Format("[Dispatcher] <<< Tool execution completed: {0}, success={1}", toolName, result != null ? result["success"] : "null"));
                }))
                {
                    Log(string.Format("[Dispatcher] FAIL: Tool {0} main thread dispatch failed", toolName));
                    return JsonError(id, string.Format("Tool {0} execution failed: main thread dispatch failed. Please check [Dispatcher] logs in tcp_server.log", toolName));
                }

                Log(string.Format("Tool {0} execution completed: {1}", toolName, result["success"]));

                // Rule hints — attached as data.rule_check; error level also downgraded to hint, doesn't change success
                AttachRuleHints(result, ruleResult, toolName);

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = result
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Tool execution failed: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Attach rule check results to result.data.rule_check.
        ///
        /// This method is the sole enforcement point for the "rules only hint" constraint:
        /// regardless of the rule verdict, it only writes data fields, returns void,
        /// and the caller never changes success or interrupts the flow based on this.
        ///
        /// Output shape:
        ///   data.rule_check = {
        ///     count:       number of reports (node omitted when 0)
        ///     issues:      [ "Hole edge clearance 1.2mm < 2x hole diameter 6.0mm", ... ]   ← error + warning combined
        ///     suggestions:     [ "Recommended clearance >= 6.0mm (2x diameter)", ... ]   ← optional
        ///     has_error_severity: true/false  ← whether an error-severity rule was hit.
        ///                          for callers to judge severity; this field triggers no interception.
        ///   }
        /// </summary>
        private void AttachRuleHints(JObject result, Rules.RuleValidateResult ruleResult, string toolName)
        {
            if (result == null || ruleResult == null)
                return;

            try
            {
                // Error level (Blockers) and warning level (Warnings) merged into same issues list —
                // to callers both are just "hints", no differentiated handling
                var issues = new JArray();
                foreach (var b in ruleResult.Blockers) issues.Add(b);
                foreach (var w in ruleResult.Warnings) issues.Add(w);

                if (issues.Count == 0 && ruleResult.Suggestions.Count == 0)
                    return;

                var gdata = result["data"] as JObject;
                if (gdata == null)
                {
                    gdata = new JObject();
                    result["data"] = gdata;
                }

                var rc = new JObject();
                rc["count"] = issues.Count;
                rc["issues"] = issues;
                if (ruleResult.Suggestions.Count > 0)
                    rc["suggestions"] = new JArray(ruleResult.Suggestions);
                rc["has_error_severity"] = ruleResult.Blockers.Count > 0;
                gdata["rule_check"] = rc;

                Log(string.Format("[RuleEngine] {0}: {1} hints (error-level {2})",
                    toolName, issues.Count, ruleResult.Blockers.Count));
            }
            catch (Exception ex)
            {
                // Hint error must never affect tool result — silently degrade to a log entry
                Log(string.Format("[RuleEngine] Failed to attach hint, ignored: {0}", ex.Message));
            }
        }

        /// <summary>
        /// List all available tools
        /// </summary>
        private string HandleListTools(int id, JToken rawParams)
        {
            try
            {
                var toolNames = _toolRegistry.ListToolNames();
                var toolList = new List<object>();
                foreach (var name in toolNames)
                {
                    var tool = _toolRegistry.GetTool(name);
                    if (tool != null)
                    {
                        toolList.Add(new { name = tool.Name, description = tool.Description });
                    }
                }

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { tools = toolList, count = toolList.Count }
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Failed to list tools: {0}", ex.Message));
            }
        }

        private string JsonError(int id, string message)
        {
            return JsonProtocol.Serialize(new ResponseMessage { Id = id, Error = message });
        }

