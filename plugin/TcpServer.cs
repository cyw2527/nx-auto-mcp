        /// <summary>
        /// Measure area/volume/distance
        /// Corresponds to scenario 2: query model info
        ///
        /// Parameters:
        ///   measure_type — "area", "volume", "distance"
        ///   target_tag   — Target object tag (face/body/edge)
        ///   target_tag2  — Second target tag (only needed for distance)
        /// </summary>
        private string HandleMeasure(int id, JToken rawParams)
        {
            try
            {
                dynamic workPart = _session.Parts.Work;
                if (workPart == null)
                    return JsonError(id, "No active workpiece");

                string measureType = "area";
                int targetTag = 0;
                int targetTag2 = 0;

                if (rawParams is JObject)
                {
                    var jObj = (JObject)rawParams;
                    if (jObj["measure_type"] != null)
                        measureType = jObj["measure_type"].Value<string>().ToLower();
                    if (jObj["target_tag"] != null)
                        targetTag = jObj["target_tag"].Value<int>();
                    if (jObj["target_tag2"] != null)
                        targetTag2 = jObj["target_tag2"].Value<int>();
                }

                if (targetTag <= 0)
                    return JsonError(id, "Missing or invalid target_tag parameter");

                if (measureType == "area")
                {
                    // Measure face area: traverse body to find face matching tag, call face.GetArea()
                    dynamic face = FindFaceByTag(workPart, targetTag);
                    if (face == null)
                        return JsonError(id, string.Format("Face not found: tag={0}", targetTag));

                    double area = (double)face.GetArea();

                    return JsonProtocol.Serialize(new ResponseMessage
                    {
                        Id = id,
                        Result = new { measure_type = "area", value = area, unit = "mm^2", target_tag = targetTag }
                    });
                }
                else if (measureType == "volume")
                {
                    // Measure body volume: NX2412 GetMassProperties removed -> MeasureHelpers (GetBodyProperties/UF fallback)
                    dynamic body = FindBodyByTag(workPart, targetTag);
                    if (body == null)
                        return JsonError(id, string.Format("Solid not found: tag={0}", targetTag));

                    var mp = NxMcpPlugin.Tools.Measure.MeasureHelpers.GetBodyMassProps(_session, body);
                    double volume = mp.Volume;

                    return JsonProtocol.Serialize(new ResponseMessage
                    {
                        Id = id,
                        Result = new { measure_type = "volume", value = volume, unit = "mm^3", target_tag = targetTag }
                    });
                }
                else if (measureType == "distance")
                {
                    // Measure shortest distance between two objects: use MeasureManager.NewDistance
                    if (targetTag2 <= 0)
                        return JsonError(id, "Distance measurement needs target_tag2 parameter");

                    dynamic obj1 = FindFaceByTag(workPart, targetTag);
                    if (obj1 == null)
                        obj1 = FindEdgeByTag(workPart, targetTag);
                    if (obj1 == null)
                        return JsonError(id, string.Format("Object not found: tag={0}", targetTag));

                    dynamic obj2 = FindFaceByTag(workPart, targetTag2);
                    if (obj2 == null)
                        obj2 = FindEdgeByTag(workPart, targetTag2);
                    if (obj2 == null)
                        return JsonError(id, string.Format("Object not found: tag={0}", targetTag2));

                    // NX2412: MeasureManager.NewDistance requires unit parameter
                    dynamic lengthUnit = workPart.UnitCollection.FindObject("MilliMeter");
                    dynamic measure = workPart.MeasureManager.NewDistance(lengthUnit, obj1, obj2);
                    double distance = (double)measure.Value;

                    return JsonProtocol.Serialize(new ResponseMessage
                    {
                        Id = id,
                        Result = new
                        {
                            measure_type = "distance",
                            value = distance,
                            unit = "mm",
                            target_tag = targetTag,
                            target_tag2 = targetTag2
                        }
                    });
                }
                else
                {
                    return JsonError(id, string.Format("Unsupported measure_type: {0}. Supported: area, volume, distance", measureType));
                }
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Measurement failed: {0}", ex.Message));
            }
        }

        /// <summary>
        /// List feature tree
        /// Corresponds to scenario 2: query model info
        ///
        /// Parameters (optional):
        ///   feature_type — Filter by type (e.g. "Hole", "Extrude"), return all if empty
        /// </summary>
        private string HandleListFeatures(int id, JToken rawParams)
        {
            try
            {
                dynamic workPart = _session.Parts.Work;
                if (workPart == null)
                    return JsonError(id, "No active workpiece");

                string featureType = null;
                if (rawParams is JObject)
                {
                    var jObj = (JObject)rawParams;
                    if (jObj["feature_type"] != null)
                        featureType = jObj["feature_type"].Value<string>();
                }

                var features = new List<object>();
                int totalCount = 0;

                foreach (dynamic feature in workPart.Features)
                {
                    if (feature == null) continue;
                    totalCount++;

                    string fName = "";
                    string fType = "";
                    int fTag = 0;
                    try { fName = feature.FeatureName; } catch { }
                    try { fType = feature.FeatureType; } catch { }
                    try { fTag = (int)feature.Tag; } catch { }

                    // Filter by type
                    if (!string.IsNullOrEmpty(featureType))
                    {
                        if (fType == null || fType.IndexOf(featureType, StringComparison.OrdinalIgnoreCase) < 0)
                            continue;
                    }

                    features.Add(new
                    {
                        tag = fTag,
                        name = fName,
                        type = fType
                    });
                }

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { features, count = features.Count, total = totalCount }
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Failed to list features: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Modify parameter expression
        /// Corresponds to scenario 6: parametric design
        ///
        /// Parameters:
        ///   expression_name — Expression name (e.g. "p0", "width")
        ///   new_value       — New value (numeric or string expression)
        /// </summary>
        private string HandleModifyExpression(int id, JToken rawParams)
        {
            try
            {
                dynamic workPart = _session.Parts.Work;
                if (workPart == null)
                    return JsonError(id, "No active workpiece");

                string expressionName = null;
                string newValue = null;

                if (rawParams is JObject)
                {
                    var jObj = (JObject)rawParams;
                    if (jObj["expression_name"] != null)
                        expressionName = jObj["expression_name"].Value<string>();
                    if (jObj["new_value"] != null)
                    {
                        var valToken = jObj["new_value"];
                        newValue = valToken.Type == JTokenType.String
                            ? valToken.Value<string>()
                            : valToken.ToString();
                    }
                }

                if (string.IsNullOrEmpty(expressionName))
                    return JsonError(id, "Missing expression_name parameter");

                if (string.IsNullOrEmpty(newValue))
                    return JsonError(id, "Missing new_value parameter");

                // Find expression
                dynamic expression = null;
                try
                {
                    expression = workPart.Expressions.FindObject(expressionName);
                }
                catch
                {
                    return JsonError(id, string.Format("Expression not found: {0}", expressionName));
                }

                if (expression == null)
                    return JsonError(id, string.Format("Expression not found: {0}", expressionName));

                // Save old value for return
                string oldValue = "";
                try { oldValue = expression.RightHandSide; } catch { }

                // Set new value
                expression.RightHandSide = newValue;

                // Update model (NX2412: Part.Update() doesn't exist, NX auto-updates expressions)
                try { workPart.Update(); } catch { }

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new
                    {
                        success = true,
                        expression_name = expressionName,
                        old_value = oldValue,
                        new_value = newValue
                    }
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Failed to modify expression: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Export STEP/IGES
        /// Corresponds to scenario 5: design iteration
        ///
        /// Parameters:
        ///   format    — "step" or "iges"
        ///   file_path — Export file full path
        /// </summary>
        private string HandleExport(int id, JToken rawParams)
        {
            try
            {
                dynamic workPart = _session.Parts.Work;
                if (workPart == null)
                    return JsonError(id, "No active workpiece");

                string format = "step";
                string filePath = null;

                if (rawParams is JObject)
                {
                    var jObj = (JObject)rawParams;
                    if (jObj["format"] != null)
                        format = jObj["format"].Value<string>().ToLower();
                    if (jObj["file_path"] != null)
                        filePath = jObj["file_path"].Value<string>();
                }

                if (string.IsNullOrEmpty(filePath))
                    return JsonError(id, "Missing file_path parameter");

                string lowerFormat = format != null ? format.ToLower() : "step";

                if (lowerFormat == "step")
                {
                    // STEP export: use DexManager (NX2412 standard method)
                    dynamic creator = _session.DexManager.CreateStepCreator();
                    try
                    {
                        creator.OutputFile = filePath;
                        creator.Apply();

                        return JsonProtocol.Serialize(new ResponseMessage
                        {
                            Id = id,
                            Result = new { success = true, format = "step", file_path = filePath }
                        });
                    }
                    finally
                    {
                        try { creator.Destroy(); } catch { }
                    }
                }
                else if (lowerFormat == "iges")
                {
                    // IGES export: use DexManager (NX2412 standard method)
                    dynamic creator = _session.DexManager.CreateIgesCreator();
                    try
                    {
                        creator.OutputFile = filePath;
                        creator.Apply();

                        return JsonProtocol.Serialize(new ResponseMessage
                        {
                            Id = id,
                            Result = new { success = true, format = "iges", file_path = filePath }
                        });
                    }
                    finally
                    {
                        try { creator.Destroy(); } catch { }
                    }
                }
                else
                {
                    return JsonError(id, string.Format("Unsupported export format: {0}. Supported: step, iges", format));
                }
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Export failed: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Undo last step
        /// Corresponds to global function
        ///
        /// Use Session.Undo() to undo most recent visible UndoMark.
        /// No parameters needed.
        /// </summary>
        private string HandleUndo(int id, JToken rawParams)
        {
            try
            {
                Log("HandleUndo: Starting undo execution");
                Log(string.Format("HandleUndo: Session type = {0}", _session.GetType().FullName));

                // NX2412: Session.Undo() doesn't exist
                // Use UndoLastNVisibleMarks or UndoToLastVisibleMark instead
                bool marksRecycled;
                bool undoUnavailable;

                try
                {
                    Log("HandleUndo: Try UndoLastNVisibleMarks");
                    // Try 3-parameter version first (NX2412)
                    _session.UndoLastNVisibleMarks(1, out marksRecycled, out undoUnavailable);
                    Log(string.Format("HandleUndo: UndoLastNVisibleMarks succeeded, undoUnavailable={0}", undoUnavailable));
                    if (undoUnavailable)
                        return JsonError(id, "No operations to undo");
                }
                catch (Exception ex1)
                {
                    Log(string.Format("HandleUndo: UndoLastNVisibleMarks failed: {0}", ex1.Message));
                    Log("HandleUndo: Try UndoToLastVisibleMark");
                    // Fallback to UndoToLastVisibleMark (available since NX 3.0)
                    _session.UndoToLastVisibleMark();
                    Log("HandleUndo: UndoToLastVisibleMark succeeded");
                }

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { success = true, message = "Last operation undone" }
                });
            }
            catch (Exception ex)
            {
                Log(string.Format("HandleUndo: Final exception: {0}", ex.ToString()));
                return JsonError(id, string.Format("Undo failed: {0}", ex.Message));
            }
        }

        /// <summary>
        /// Get expression list
        /// Corresponds to scenario 6: parametric design
        ///
        /// Parameters (optional):
        ///   name_filter — Filter by name (partial match), return all if empty
        /// </summary>
        private string HandleGetParameters(int id, JToken rawParams)
        {
            try
            {
                dynamic workPart = _session.Parts.Work;
                if (workPart == null)
                    return JsonError(id, "No active workpiece");

                string nameFilter = null;
                if (rawParams is JObject)
                {
                    var jObj = (JObject)rawParams;
                    if (jObj["name_filter"] != null)
                        nameFilter = jObj["name_filter"].Value<string>();
                }

                var expressions = new List<object>();

                foreach (dynamic expr in workPart.Expressions)
                {
                    if (expr == null) continue;

                    string eName = "";
                    string eValue = "";
                    string eUnits = "";

                    try { eName = expr.Name; } catch { }
                    try { eValue = expr.RightHandSide; } catch { }

                    // Get unit name
                    try
                    {
                        dynamic units = expr.Units;
                        if (units != null)
                            eUnits = units.Name;
                    }
                    catch { }

                    // Filter by name
                    if (!string.IsNullOrEmpty(nameFilter))
                    {
                        if (eName == null || eName.IndexOf(nameFilter, StringComparison.OrdinalIgnoreCase) < 0)
                            continue;
                    }

                    expressions.Add(new
                    {
                        name = eName,
                        value = eValue,
                        units = eUnits
                    });
                }

                return JsonProtocol.Serialize(new ResponseMessage
                {
                    Id = id,
                    Result = new { expressions, count = expressions.Count }
                });
            }
            catch (Exception ex)
            {
                return JsonError(id, string.Format("Failed to get expression list: {0}", ex.Message));
            }
        }

