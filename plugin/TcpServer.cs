    /// <summary>
    /// TCP JSON line protocol server
    ///
    /// Listens on localhost:1977, handles requests from MCP Server.
    /// Each connection handled independently, supports pipeline reuse.
    ///
    /// Protocol:
    ///   Request:  JSON one line \n
    ///   Response: JSON one line \n
    ///
    /// Registry pattern:
    ///   - Use Dictionary to store method handlers
    ///   - Support dynamically adding new methods (auto-generated by sdk-forge)
    ///   - Eliminate hardcoded switch statements
    ///
    /// Supported methods:
    ///   ping              → Health check
    ///   get_selection     → Get current selection
    ///   get_model_summary → Get model summary
    ///   tool              → Execute tool (unified entry point)
    ///   list_tools        → List available tools
    ///   measure           → Measure area/volume/distance
    ///   list_features     → List feature tree
    ///   modify_expression → Modify parameter expression
    ///   export            → Export STEP/IGES
    ///   undo              → Undo last step
    ///   get_parameters    → Get expression list
    /// </summary>
    public class TcpServer
    {
        private dynamic _session;
        private dynamic _ui;
        private SelectionMonitor _monitor;
        private TcpListener _listener;
        private volatile bool _running;
        public bool IsRunning { get { return _running; } }
        private ToolRegistry _toolRegistry;

        /// <summary>
        /// Engineering rules engine — performs process knowledge checks on tool parameters
        /// (hole clearance / wall thickness / depth-to-diameter ratio / thread matching etc.).
        /// Rule table (15 rules) in rules/rules_config.json, deployed alongside DLL to startup\rules\.
        ///
        /// ★ Only hints, never blocks: check results uniformly attached as data.rule_check in response.
        ///   Even if rule verdict is error level, it's only hint text — never changes success, never rejects execution.
        ///   Reason: rules contain items dependent on geometry estimation;
        ///   strict enforcement would harm legitimate operations
        ///   (e.g. rule-extrude-positive-distance requires positive extrusion, but NX allows negative extrusion).
        /// </summary>
        private Rules.RuleEngine _rules;

        /// <summary>
        /// Maximum message length limit (1MB) — prevent memory exhaustion attacks
        /// </summary>
        private const int MAX_MESSAGE_LENGTH = 1024 * 1024;

        /// <summary>
        /// Method handler registry
        /// Key: Method name (e.g. "ping", "tool")
        /// Value: Handler function (receives id and rawParams, returns JSON string)
        /// </summary>
        private Dictionary<string, Func<int, JToken, string>> _methodHandlers;

        public TcpServer(dynamic session, dynamic ui, SelectionMonitor monitor)
        {
            _session = session;
            _ui = ui;
            _monitor = monitor;

            // Initialize tool registry
            _toolRegistry = ToolRegistry.Instance;
            _toolRegistry.RegisterAll();
            Log(string.Format("Tool registry initialized: {0} tools", _toolRegistry.ToolCount));

            // Rule engine — read-only hints, consumption point is rule_check in HandleTool
            _rules = new Rules.RuleEngine(_session);

            // Initialize method registry
            _methodHandlers = new Dictionary<string, Func<int, JToken, string>>();

            // Core methods
            RegisterMethod("ping", HandlePing);
            RegisterMethod("get_selection", HandleGetSelection);
            RegisterMethod("get_model_summary", HandleGetModelSummary);
            RegisterMethod("tool", HandleTool);
            RegisterMethod("list_tools", HandleListTools);

            // Methods implemented via NX API
            RegisterMethod("measure", HandleMeasure);
            RegisterMethod("list_features", HandleListFeatures);
            RegisterMethod("modify_expression", HandleModifyExpression);
            RegisterMethod("export", HandleExport);
            RegisterMethod("undo", HandleUndo);
            RegisterMethod("get_parameters", HandleGetParameters);

            Log(string.Format("Method registry initialized: {0} methods", _methodHandlers.Count));
        }

        /// <summary>
        /// Register new method handler
        ///
        /// Usage:
        ///   server.RegisterMethod("my_method", MyHandler);
        ///
        /// Code auto-generated by sdk-forge:
        ///   server.RegisterMethod("new_method", GeneratedHandler);
        /// </summary>
        /// <param name="method">Method name (e.g. "create_pocket")</param>
        /// <param name="handler">Handler function</param>
        public void RegisterMethod(string method, Func<int, JToken, string> handler)
        {
            if (string.IsNullOrEmpty(method))
                throw new ArgumentException("Method name cannot be empty");

            if (handler == null)
                throw new ArgumentNullException("handler");

            _methodHandlers[method] = handler;
        }

        /// <summary>
        /// Get list of registered methods
        /// </summary>
        public IEnumerable<string> GetRegisteredMethods()
        {
            return _methodHandlers.Keys;
        }

        /// <summary>
        /// Check if method is registered
        /// </summary>
        public bool HasMethod(string method)
        {
            return _methodHandlers.ContainsKey(method);
        }

        /// <summary>
        /// Start TCP listening
        /// </summary>
        /// <param name="host">Bind address, localhost only</param>
        /// <param name="port">Port, default 1977</param>
        public void Start(string host = "127.0.0.1", int port = 1977)
        {
            _listener = new TcpListener(IPAddress.Parse(host), port);
            _listener.Start();
            _running = true;

            Log(string.Format("TCP service started: {0}:{1}", host, port));

            // Connection acceptance loop — each HandleClient round is synchronous
            // Simple scenario handles one connection at a time (can be changed to async later)
            while (_running)
            {
                try
                {
                    var client = _listener.AcceptTcpClient();
                    Log(string.Format("Client connected: {0}", client.Client.RemoteEndPoint));
                    // Use thread pool to avoid blocking
                    System.Threading.ThreadPool.QueueUserWorkItem(_ =>
                    {
                        try { HandleClient(client); }
                        catch (Exception ex) { Log(string.Format("Client exception: {0}", ex.Message)); }
                        finally
                        {
                            try { client.Close(); } catch { }
                            Log("Client disconnected");
                        }
                    });
                }
                catch (SocketException)
                {
                    if (_running)
                        throw;
                    // Normal shutdown
                }
                catch (Exception ex)
                {
                    Log(string.Format("Accept connection exception: {0}", ex.Message));
                }
            }
        }

        /// <summary>
        /// Handle single client — line protocol
        /// </summary>
        private void HandleClient(TcpClient client)
        {
            try
            {
                var stream = client.GetStream();
                var encoding = new UTF8Encoding(false);

                // Simple byte-level line reading, avoid StreamReader blocking or BOM writing
                var buffer = new List<byte>();
                int b;
                while ((b = stream.ReadByte()) != -1)
                {
                    if (b == '\n')
                    {
                        var line = encoding.GetString(buffer.ToArray()).TrimEnd('\r');
                        buffer.Clear();
                        if (string.IsNullOrWhiteSpace(line)) continue;

                        Log(string.Format("Received raw message: {0}", line));
                        string response;
                        try
                        {
                            response = ProcessMessage(line);
                        }
                        catch (Exception ex)
                        {
                            response = JsonProtocol.Serialize(new ResponseMessage { Id = 0, Error = "Processing exception: " + ex.Message });
                            Log(string.Format("ProcessMessage exception: {0}\n{1}", ex.Message, ex.StackTrace));
                        }

                        var respBytes = encoding.GetBytes(response + "\n");
                        stream.Write(respBytes, 0, respBytes.Length);
                        stream.Flush();
                        Log(string.Format("Sent {0} bytes response", respBytes.Length));
                    }
                    else
                    {
                        // Safety check: limit message length to prevent memory exhaustion
                        if (buffer.Count >= MAX_MESSAGE_LENGTH)
                        {
                            Log(string.Format("Message length exceeds limit ({0} bytes), discarded", MAX_MESSAGE_LENGTH));
                            buffer.Clear();
                            // Read until newline, discard remaining data
                            while ((b = stream.ReadByte()) != -1 && b != '\n') { }
                            continue;
                        }
                        buffer.Add((byte)b);
                    }
                }
            }
            catch (Exception ex)
            {
                if (IsConnectionReset(ex))
                {
                    // Client disconnected gracefully — normal behavior
                    Log("Client disconnected (connection reset by peer)");
                }
                else
                {
                    Log(string.Format("HandleClient exception: {0}\n{1}", ex.Message, ex.StackTrace));
                }
            }
        }

        /// <summary>
        /// Determine if exception is client actively disconnecting
        /// </summary>
        private static bool IsConnectionReset(Exception ex)
        {
            // Check common client disconnect error codes
            if (ex.InnerException != null && ex.InnerException is System.Net.Sockets.SocketException)
            {
                var socketEx = (System.Net.Sockets.SocketException)ex.InnerException;
                // 10054 = WSAECONNRESET (remote host forcibly closed)
                // 10053 = WSAECONNABORTED (software caused connection abort)
                return socketEx.ErrorCode == 10054 || socketEx.ErrorCode == 10053;
            }
            return ex.Message.Contains("远程主机") || ex.Message.Contains("remote host") || ex.Message.Contains("connection was closed");
        }

        /// <summary>
        /// Process a JSON message (table lookup pattern)
        /// </summary>
        private string ProcessMessage(string json)
        {
            try
            {
                var method = JsonProtocol.ExtractMethod(json);
                var id = JsonProtocol.ExtractId(json);
                var rawParams = JsonProtocol.ExtractParams(json);

                if (string.IsNullOrEmpty(method))
                {
                    return JsonProtocol.Serialize(new ResponseMessage { Id = id, Error = "Missing method field" });
                }

                Log(string.Format("Received: {0} (id={1})", method, id));

                // Table lookup pattern
                if (!_methodHandlers.ContainsKey(method))
                {
                    return JsonProtocol.Serialize(new ResponseMessage
                    {
                        Id = id,
                        Error = string.Format("Unknown method: {0}. Supported: {1}", method, string.Join(", ", _methodHandlers.Keys))
                    });
                }

                // Marshal all handler calls to NX main thread
                // NXOpen API requires main thread execution, otherwise silent failure or crash
                Log(string.Format("[Dispatcher] Pre-dispatch check: IsInitialized={0}, method={1}",
                    MainThreadDispatcher.IsInitialized, method));
                string handlerResult = null;
                if (!MainThreadDispatcher.Invoke(() => {
                    Log(string.Format("[Dispatcher] >>> Execute on main thread: method={0}", method));
                    handlerResult = _methodHandlers[method](id, rawParams);
                    Log(string.Format("[Dispatcher] <<< Execution completed: method={0}", method));
                }))
                {
                    Log(string.Format("[Dispatcher] FAIL: Method {0} main thread dispatch failed", method));
                    return JsonProtocol.Serialize(new ResponseMessage
                    {
                        Id = id,
                        Error = string.Format("Method {0} main thread dispatch failed. Please check [Dispatcher] logs in tcp_server.log", method)
                    });
                }
                return handlerResult;
            }
            catch (Exception ex)
            {
                return JsonProtocol.Serialize(new ResponseMessage { Id = 0, Error = string.Format("Message processing exception: {0}", ex.Message) });
            }
        }

